export const getSEOForRoute = (pathname) => {
    // Clean up the pathname
    const cleanPath = pathname.split('?')[0].replace(/\/$/, '');

    // Check for exact match
    if (routeSEO[cleanPath]) {
        return { ...defaultSEO, ...routeSEO[cleanPath] };
    }

    // Check for dynamic routes (e.g., /project/:id)
    if (cleanPath.startsWith('/project/')) {
        return {
            ...defaultSEO,
            title: 'Interior Design Project Portfolio | Dsigner Studio Interiors',
            description: 'View our interior design project portfolio. Professional residential, commercial, and luxury design projects by Dsigner Studio Interiors.',
            keywords: 'interior design project, portfolio, residential project, commercial project, Hyderabad interiors',
        };
    }

    // Default fallback
    return defaultSEO;
};